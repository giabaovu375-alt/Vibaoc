// ============================================================
// VIBAO RUNTIME (Rust/WASM) — runtime/dom.rs
// A direct port of 18-runtime-event.ts to Rust/WASM, using web-sys to
// manipulate the real DOM. This is where `expr_eval`/`state` (pure
// Rust, knows nothing about the DOM) connects to a real HTML page in
// the browser.
//
// THE BIGGEST DIFFERENCE from the old JS version:
//   - JS version: each binding has a "getter" - an arbitrary JS
//     closure, free to write any expression (e.g. `() => __state.n + 1`),
//     created by `__compileExprString` (eval-ing a JS string generated
//     by codegen).
//   - Rust version: each binding has an `expr_id: usize` - pointing
//     into `expr_registry` (a Vec<Expr> loaded from JSON at boot).
//     When a value is needed, calls
//     `expr_eval::eval_tracked(shared, &expr_registry::get(id))`.
//     THERE IS NO JS STRING EVAL ANYWHERE - all computation runs in
//     pure Rust inside WASM.
//
// Since every DOM API (`querySelectorAll`, `classList`, `dataset`...)
// is FFI through web-sys/wasm-bindgen, this file has far more
// `.ok()?`/`unwrap_or` than state.rs/expr_eval.rs (pure Rust) - this is
// the inherent cost of wrapping an API that's "freely JS-typed" (the
// DOM can always be null/nonexistent) into a statically-typed API,
// unavoidable.


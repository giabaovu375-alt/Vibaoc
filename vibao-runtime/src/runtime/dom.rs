/// dong_modal(id) - hides the corresponding overlay, restoring body
/// scroll if no other modal is still open.
pub fn close_modal(id: &str) {
    let doc = document();
    let el_id = format!("vb-modal-{}", id);
    let Some(overlay) = doc.get_element_by_id(&el_id) else {
        return;
    };
    if let Ok(html_el) = overlay.dyn_into::<HtmlElement>() {
        let _ = html_el.style().set_property("display", "none");
    }
    // Checks whether any other modal is still open (display != "none")
    // - simplified compared to the JS version (no separate tracking
    // registry), scanning the DOM directly since the number of modals
    // on a page is typically very small.
    let any_open = doc
        .query_selector_all("[id^='vb-modal-']")
        .ok()
        .map(|list| {
            (0..list.length()).any(|i| {
                list.item(i)
                    .and_then(|n| n.dyn_into::<HtmlElement>().ok())
                    .map(|el| el.style().get_property_value("display").unwrap_or_default() != "none")
                    .unwrap_or(false)
            })
        })
        .unwrap_or(false);

    if !any_open {
        if let Some(body) = doc.body() {
            let _ = body.style().set_property("overflow", "");
        }
    }
}


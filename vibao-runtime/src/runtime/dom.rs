// ════════════════════════════════════════════════════════════
// 8. BOOT — the startup point, called from JS via __vb.boot({...})
// ════════════════════════════════════════════════════════════
// Equivalent to the final section of 18-runtime-event.ts (where every
// bind* was attached to DOMContentLoaded). Here, instead of listening
// for DOMContentLoaded itself (the JS script tag is placed at the end
// of <body>, so the DOM is always ready by the time the script runs,
// no extra wait needed), a `boot` function is exposed directly for
// codegen's generated JS to call as its final line:
//
//   __vb.boot({ baseURL: '...', exprRegistry: [...], actionRegistry: [...] });
//
// `#[wasm_bindgen]` auto-generates JS glue code letting this Rust
// function be called from JS like an ordinary function - this is the
// main FFI boundary between JS (now just a few minimal bootstrap
// lines) and WASM (all the real logic).

#[wasm_bindgen]
pub struct VbRuntime {
    shared: SharedState,
}

fn initialize_global_vars(shared: &SharedState, global_vars: &[(String, Expr)]) {
    // Evaluate + insert sequentially so a `bien` declared earlier can be
    // referenced by a later `bien`. The old map/collect form evaluated
    // every expression before inserting any of them, so sibling variable
    // references all observed Null.
    for (name, expr) in global_vars {
        let value = super::expr_eval::eval(shared, expr);
        shared.borrow_mut().set_var(name, value);
    }
}

#[wasm_bindgen]
impl VbRuntime {
    /// Starts the runtime: loads the expr + action registries, sets
    /// base_url, binds every existing binding in the current DOM
    /// (`<body>`). `opts_json` is a JSON string of the form
    /// `{ "baseURL": "...", "exprRegistry": [...], "actionRegistry": [...] }`.
    #[wasm_bindgen(constructor)]
    pub fn new(opts_json: &str) -> VbRuntime {
        // BUG FIX (added during route-navigation white-screen
        // investigation): there was no console_error_panic_hook anywhere
        // in this crate. By default, a Rust panic inside WASM produces
        // NO console output at all in release builds - the JS side just
        // sees the module trap silently, which matches EXACTLY the
        // reported symptom (white screen, zero errors, zero console
        // output) when calling dieu_huong("/path/:id") to a dynamic
        // route. This must be the very first line of the constructor so
        // it's active before ANY other code in this function (including
        // JSON parsing, expr registry loading, and router::boot_router)
        // has a chance to panic silently.
        console_error_panic_hook::set_once();

        #[derive(serde::Deserialize)]
        struct BootOpts {
            #[serde(rename = "exprRegistry")]
            expr_registry: Vec<Expr>,
            #[serde(rename = "actionRegistry", default)]
            action_registry: Vec<Vec<vibao_ast::Action>>,
            #[serde(rename = "baseURL")]
            base_url: String,
            // BUG ALREADY FIXED: `state $x = <value>` used to be
            // generated by codegen as a JS line "const x = <value>;"
            // SITTING INSIDE A SEPARATE IIFE, with no connection to
            // VbRuntime whatsoever - WASM always booted with a
            // completely empty `State { state: HashMap::new(), .. }`.
            // Every read of a variable never set_state()'d returned
            // VbValue::Null (see State::get_state/peek_state), losing
            // EVERY initial "state" value - not a rare bug, this was
            // 100% of the time behavior every time the app started.
            // This new field receives the list (variable name, initial
            // Expr) that the compiler now embeds in optsJson - see the
            // corresponding fix in vibaoc/src/codegen/mod.rs.
            #[serde(rename = "pageInitialState", default)]
            page_initial_state: Vec<(String, Vec<(String, Expr)>)>,
            // BUG-19 ALREADY FIXED (see RUNTIME_BOUNDARY_BUGS.md): a
            // variable declared WITHOUT the `state` keyword (the syntax
            // "$ten = gia_tri", unlike "state $ten = ..." in the
            // pageInitialState field above) used to be correctly
            // recorded by the compiler but was NEVER serialized and
            // sent to the runtime - even though
            // State::init_global_vars() AND the `vars` field (kept
            // separate from `state`, non-reactive) had already been
            // fully written beforehand, only missing this call. This
            // new field receives the list (variable name, initial Expr)
            // that the compiler now embeds in optsJson - see the
            // corresponding fix in
            // vibaoc/src/codegen/mod.rs::gen_app_js.
            #[serde(rename = "globalVars", default)]
            global_vars: Vec<(String, Expr)>,
        }

        let opts: BootOpts = match serde_json::from_str(opts_json) {
            Ok(o) => o,
            Err(err) => {
                super::log::error(&format!("[ViBao] boot() received invalid JSON: {}", err));
                BootOpts {
                    expr_registry: Vec::new(),
                    action_registry: Vec::new(),
                    base_url: String::new(),
                    page_initial_state: Vec::new(),
                    global_vars: Vec::new(),
                }
            }
        };

        expr_registry::load_from_json(
            &serde_json::to_string(&opts.expr_registry).unwrap_or_else(|_| "[]".to_string()),
        );
        super::action_registry::load_from_json(
            &serde_json::to_string(&opts.action_registry).unwrap_or_else(|_| "[]".to_string()),
        );

        let shared = state::new_shared_state();
        shared.borrow_mut().set_base_url(opts.base_url);

        // BUG-19 ALREADY FIXED: loads "$ten = gia_tri" (without
        // `state`) into the `vars` field (NOT reactive - matching the
        // "local constant" meaning of the non-`state` syntax, unlike
        // `state` above). Loaded after the runtime has created its
        // State and set every state value above, so if a `bien`'s
        // initializer expression references a `state` variable (e.g.
        // "$gia_giam = $gia_goc * 0.9", where $gia_goc is state), the
        // eval() here correctly reads the $gia_goc value already
        // set_state()'d above, not Null. Uses eval() (not
        // eval_tracked()) for the same reason as pageInitialState -
        // this is initialization time, with no subscriber yet to track.
        //
        // The `vars` field is NOT reset when navigating pages within
        // the SPA (see init_global_vars() - "runs once at app boot") -
        // matching the app-wide/`ung_dung`-level meaning of
        // `app.variables`, and also making sense for a `bien` nested
        // inside a specific page: its value doesn't change based on
        // state, so it doesn't need resetting per page.
        initialize_global_vars(&shared, &opts.global_vars);

        // Does NOT bind_subtree() the whole <body> here - doing so would
        // DOUBLE-bind the currently active page (once here for the
        // whole body, once more inside router::boot_router when it
        // activates the correct page). router::boot_router() is the
        // ONLY place that calls bind_subtree, and it knows to bind
        // exactly the ONE page's (.vb-page) subtree matching the
        // current URL - other pages (not yet active) don't need binding
        // right away, and will bind themselves the first time the
        // router navigates to them.
        shared.borrow_mut().set_page_initial_states(opts.page_initial_state);
        super::router::boot_router(&shared);

        VbRuntime { shared }
    }

    /// Exposes evalExpr(id) for JS to call directly if needed (e.g. the
    /// debug console, or an action handler wanting to recompute a
    /// registered expr's current value without going through a
    /// binding). Does NOT track dependencies (uses `eval`, not
    /// `eval_tracked`) since a call from the JS console/an action isn't
    /// running inside an active subscriber's context.
    #[wasm_bindgen(js_name = evalExpr)]
    pub fn eval_expr(&self, id: usize) -> JsValue {
        let v = eval_expr_id(&self.shared, id);
        v.to_js_value()
    }
}


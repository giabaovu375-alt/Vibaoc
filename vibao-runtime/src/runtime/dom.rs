/// Visits every element in `root` (including `root` itself) matching
/// `selector`, equivalent to `root.querySelectorAll(selector)` + adding
/// root itself if it also matches - the original JS version used the
/// same approach to bind both the root node and its descendants when
/// mounting a new subtree (e.g. after rendering a loop).
fn query_all(root: &Element, selector: &str) -> Vec<Element> {
    let mut out = Vec::new();
    if let Ok(true) = root.matches(selector) {
        out.push(root.clone());
    }
    if let Ok(list) = root.query_selector_all(selector) {
        for i in 0..list.length() {
            if let Some(node) = list.item(i) {
                if let Ok(el) = node.dyn_into::<Element>() {
                    out.push(el);
                }
            }
        }
    }
    out
}

/// True if `el` sits inside (is a real descendant of) a
/// `[data-vb-component]` DIFFERENT from `root` - meaning `el` belongs
/// to an @the component instance NESTED inside `root`, not directly
/// belonging to `root`.
///
/// NEEDED because `query_all(root, selector)` (querySelectorAll) scans
/// THROUGH every descendant, with no concept of "stopping at a
/// component boundary" - if `bind_subtree(root=page)` scanned
/// `[data-vb-text]` across the entire subtree directly, it would hit
/// text inside a child component too (e.g. `ThanhDieuHuong` containing
/// `text($tieu_de)`). Without excluding this, that text would get bound
/// TWICE: once here (WRONG - `component_id` would be `None` or the
/// GRANDPARENT component's id, not the direct PARENT's) and once
/// correctly via `bind_component()` -> recursing into
/// `bind_subtree(el=child_component, ..., Some(correct_id))`.
/// Double-binding means 2 subscribers for the same DOM node - wasteful,
/// and the WRONG closure (bound here first) would set the WRONG
/// text/attr as soon as it runs.
fn is_inside_nested_component(el: &Element, root: &Element) -> bool {
    let mut current: Option<Element> = el.parent_element();
    while let Some(ancestor) = current {
        // Compares IDENTITY (the same real DOM node), not content -
        // uses Node::is_same_node() (a standard DOM API) instead of
        // relying on a derived `PartialEq` for `web_sys::Element` (not
        // guaranteed to exist depending on the web-sys version, and
        // even if it did, is_same_node() is clearer and more explicit
        // about intent).
        if ancestor.is_same_node(Some(root.as_ref())) {
            return false; // reached root without hitting another component -> not nested
        }
        if ancestor.has_attribute(ATTR_COMPONENT) {
            return true; // hit a different component boundary BEFORE reaching root
        }
        current = ancestor.parent_element();
    }
    false // el is not a descendant of root via parent_element (an unusual case) - treated as not nested, keeping the old behavior (normal binding) unchanged
}

/// BUG FIX (every branch of a `truong_hop`/switch was being bound at
/// once, even branches never shown - e.g. 3 branches x 5 loop items x
/// 4 props = 60 prop getters all registering/running together on first
/// bind, confirmed via debug logging to produce Null instead of the
/// real value for every one of them, and - separately - explains why
/// re-activating the page multiplied removed-node counts by 3 instead
/// of 1): `bind_subtree`'s scans (`[data-vb-loop]`, `[data-vb-if]`,
/// `[data-vb-component]`, etc.) walk the ENTIRE subtree via
/// `querySelectorAll`, which does not care about CSS `display` at all
/// - so every `vong_lap`/`neu`/component sitting inside ANY branch of a
/// `truong_hop` (including the 2 branches never shown) used to get
/// bound immediately, just like the one actually chosen. This mirrors
/// `is_inside_nested_component` above: walks up from `el` looking for a
/// `[data-vb-case]`/`[data-vb-default]` ancestor BEFORE reaching `root`
/// - if found, `el` sits inside some branch of a switch, and binding it
/// from the OUTER scan is wrong; the switch itself (`bind_switch`) is
/// now responsible for binding exactly the one branch it decides to
/// show, via its own `bind_subtree` call scoped to that branch only
/// (see the change in `bind_switch` below).
fn is_inside_switch_case(el: &Element, root: &Element) -> bool {
    let mut current: Option<Element> = el.parent_element();
    while let Some(ancestor) = current {
        if ancestor.is_same_node(Some(root.as_ref())) {
            return false;
        }
        if ancestor.has_attribute(ATTR_CASE) || ancestor.has_attribute(ATTR_DEFAULT) {
            return true;
        }
        current = ancestor.parent_element();
    }
    false
}

/// BUG FIX (component called directly inside a `vong_lap` - e.g.
/// `vong_lap $bv trong $ds_bai_viet { TheBaiViet(tieu_de: $bv.tieu_de, ...) }`
/// - every one of its props referencing the loop item, like `$bv.tieu_de`,
/// always resolved to Null/empty inside the component's own body, even
/// though a plain text binding in the SAME loop resolved correctly;
/// confirmed via debug logging that ALL 5 `TheBaiViet` instances were
/// affected, every single time, with `prop_scope(name="bv")` firing
/// against an EMPTY `loop_scope_stack`): `bind_subtree`'s scans walk the
/// ENTIRE subtree via `querySelectorAll`, called SEPARATELY (and in this
/// order) for `[data-vb-loop]` first, THEN `[data-vb-component]` - but
/// `bind_loop` runs SYNCHRONOUSLY (via `state::subscribe`, which runs
/// its closure once immediately) and inserts its cloned, ALREADY
/// correctly-bound component instances (via
/// `bind_fragment_with_loop_frame` -> `bind_component(..., Some(frame))`)
/// as real children in the live DOM before `bind_subtree` even reaches
/// its own `[data-vb-component]` scan. That LATER scan's
/// `query_selector_all` call then finds those SAME, already-correctly-
/// bound elements again (nothing here excluded elements sitting inside
/// a loop's rendered output - only `is_inside_nested_component`/
/// `is_inside_switch_case` were checked) and calls `bind_component`
/// AGAIN, this time with the OUTER (branch/root-level) `loop_frame`
/// - which is `None` for a loop sitting directly inside a `truong_hop`
/// case - clobbering the correct, just-registered props with broken
/// getters that have no loop frame to resolve `$bv` against.
///
/// UNLIKE `is_inside_switch_case`/`is_inside_nested_component` (which
/// both look for an ANCESTOR carrying the relevant marker attribute -
/// `[data-vb-case]`/`[data-vb-default]`, `[data-vb-component]`), this
/// function CANNOT just look for an ancestor carrying `ATTR_LOOP`
/// (`[data-vb-loop]`): per `codegen/control.rs::gen_loop`, the
/// `[data-vb-loop]` anchor div in the static HTML is ALWAYS EMPTY
/// (`<div id="..." data-vb-loop="...">​</div>`) - `bind_loop` inserts
/// every rendered item as that anchor's SIBLING in the live DOM (see
/// `let parent = anchor.parent_node()` in `bind_loop`), never as its
/// CHILD. So a rendered item's element is NEVER a descendant of the
/// `[data-vb-loop]` anchor - walking its ancestors would never find
/// one, and this filter would never fire at all.
///
/// The fix: `bind_loop` now stamps a separate, runtime-only marker
/// attribute (`ATTR_LOOP_ITEM_MARKER`, never emitted by codegen) onto
/// every TOP-LEVEL element of each item it renders, right before
/// inserting it - see the doc-comment on `ATTR_LOOP_ITEM_MARKER`. This
/// function checks for that marker on `el` ITSELF first (covers the
/// exact case above: `el` IS the top-level rendered element, e.g. the
/// `TheBaiViet` div matched directly by the `[data-vb-component]`
/// selector), then walks ancestors exactly like the other 2 filters
/// (covers a rendered item whose top-level element is a wrapper
/// containing the real match somewhere deeper inside, e.g. a `khoi(...)`
/// item container holding a nested `[data-vb-text]`).
///
/// The `el == root` guard MUST run before checking `el` itself for the
/// marker: `query_all` deliberately includes `root` itself when `root`
/// matches the selector being scanned for (see `query_all`'s own
/// `root.matches(selector)` check) - this happens for a loop-of-loops
/// (e.g. example 07's nested `vong_lap $hang { vong_lap $cot { ... } }`):
/// the INNER loop's own anchor div is itself the sole top-level element
/// of the OUTER loop's item, so it correctly CARRIES the marker (it was
/// stamped as the outer loop's rendered item) - but when
/// `bind_fragment_with_loop_frame` recurses into
/// `bind_subtree(shared, &inner_anchor, ...)` with `root = inner_anchor`
/// itself, that call's OWN `[data-vb-loop]` scan must still find AND
/// bind the inner anchor (via `query_all`'s root-self-match) - it must
/// NOT be filtered out just because it also happens to carry the outer
/// loop's marker.
fn is_inside_loop(el: &Element, root: &Element) -> bool {
    if el.is_same_node(Some(root.as_ref())) {
        return false;
    }
    if el.has_attribute(ATTR_LOOP_ITEM_MARKER) {
        return true;
    }
    let mut current: Option<Element> = el.parent_element();
    while let Some(ancestor) = current {
        if ancestor.is_same_node(Some(root.as_ref())) {
            return false;
        }
        if ancestor.has_attribute(ATTR_LOOP_ITEM_MARKER) {
            return true;
        }
        current = ancestor.parent_element();
    }
    false
}


/// Reads an Expr by id from the registry, returning VbValue::Null if
/// the id is invalid - never panics (see the reasoning in
/// expr_registry.rs).
///
/// `loop_frame`: if this binding is inside a loop, this is the
/// LoopFrame snapshot FOR THAT EXACT ITEM, already packaged (via
/// `move`) into the closure calling this function - NOT read through a
/// global loop-scope stack. The function pushes this frame onto the
/// stack RIGHT BEFORE eval, and pops it RIGHT AFTER - correct no matter
/// when the closure runs (the first render, or a later independent
/// re-run once a field inside that item changes).
///
/// FIX: push/pop used to only wrap around BIND time (creating the
/// closure), not RE-RUN time (when the closure runs again independently
/// later) - meaning a re-running closure would read the wrong (or no)
/// LoopFrame, since the global stack at that moment could be carrying a
/// DIFFERENT item's frame (or be empty). The fix: each closure carries
/// its own LoopFrame (the `loop_frame` parameter here), pushing/popping
/// it itself RIGHT DURING THAT CALL - not depending on anyone having
/// pushed it beforehand.
///
/// `component_id`: EXACTLY LIKE `loop_frame` but for an @the component -
/// if this binding is inside a mounted component instance (via
/// `bind_component`, see the "BIND COMPONENT" section below), this is
/// that exact instance's id, packaged into the closure. Same reasoning
/// as loop_frame: a component's props (`register_props(id, ...)`) are
/// looked up via `component_scope_stack` (see state.rs::prop_scope) -
/// each closure must push/pop its own id itself during that call,
/// not relying on anyone having pushed it beforehand, since a closure
/// can re-run independently at any time (after binding), when the
/// global stack could be carrying a DIFFERENT component instance's
/// scope, or be empty.
/// RAII guard ensuring `push_loop_scope`/`push_component_scope` are
/// ALWAYS matched by their corresponding pop, even if the code that
/// runs between push and pop panics or returns early - Rust's `Drop`
/// runs during unwinding too (unless the panic itself aborts the
/// process, e.g. inside a `catch_unwind`-incompatible FFI boundary; not
/// a concern here since this guard's own `Drop` impl only touches plain
/// Rust data structures, no FFI).
///
/// BUG FIX: the two calls this replaces (`eval_expr_id_tracked` used to
/// push then pop by hand, with a plain `match` in between) had no such
/// guarantee - if the evaluation in between ever panicked or otherwise
/// skipped the pop lines, the pushed scope would remain on the global
/// stack forever, corrupting every subsequent unrelated lookup in the
/// same session (since `component_scope_stack`/`loop_scope_stack` are
/// shared, session-wide stacks). No confirmed panic site was found by
/// reading the code (every downstream function reached from here -
/// `eval_tracked`/`eval_inner`/`eval_readonly`/`get_field` - was
/// checked and uses `unwrap_or`/exhaustive `match`, not `unwrap()`/
/// `panic!()`), but this guard removes the entire class of risk
/// regardless, and is strictly safer than the hand-rolled push/pop it
/// replaces.
struct ScopeGuard<'a> {
    shared: &'a SharedState,
    component_id: Option<String>,
    has_loop_frame: bool,
}

impl<'a> Drop for ScopeGuard<'a> {
    fn drop(&mut self) {
        // Pops in the REVERSE order of how `eval_expr_id_tracked` used
        // to push (loop first, component second) - component first,
        // loop second - preserving the exact same LIFO behavior as
        // before, just guaranteed to run now.
        if let Some(cid) = &self.component_id {
            self.shared.borrow_mut().pop_component_scope(cid);
        }
        if self.has_loop_frame {
            self.shared.borrow_mut().pop_loop_scope();
        }
    }
}

fn eval_expr_id_tracked(
    shared: &SharedState,
    id: usize,
    loop_frame: Option<&LoopFrame>,
    component_id: Option<&str>,
) -> VbValue {
    if let Some(frame) = loop_frame {
        shared.borrow_mut().push_loop_scope(frame.clone());
    }
    if let Some(cid) = component_id {
        shared.borrow_mut().push_component_scope(cid);
    }
    // Constructed AFTER both pushes succeed, so its Drop (which pops)
    // always matches exactly what was actually pushed above - runs no
    // matter how the rest of this function exits (normal return, early
    // return, or unwinding from a panic).
    let _guard = ScopeGuard {
        shared,
        component_id: component_id.map(|s| s.to_string()),
        has_loop_frame: loop_frame.is_some(),
    };

    match expr_registry::get(id) {
        Some(expr) => expr_eval::eval_tracked(shared, &expr),
        None => {
            super::log::warn(&format!("[ViBao] expr id {} does not exist in the registry", id));
            VbValue::Null
        }
    }
    // `_guard` drops here (end of scope), popping both scopes in the
    // correct order automatically.
}

fn eval_expr_id(shared: &SharedState, id: usize) -> VbValue {
    match expr_registry::get(id) {
        Some(expr) => expr_eval::eval(shared, &expr),
        None => VbValue::Null,
    }
}

/// Parses an attribute value like "<number>" into a usize (an expr
/// id). Returns None and logs a warning if it can't be parsed - a
/// broken attribute shouldn't crash the entire page.
fn parse_expr_id(raw: &str, context: &str) -> Option<usize> {
    match raw.trim().parse::<usize>() {
        Ok(id) => Some(id),
        Err(_) => {
            super::log::warn(&format!(
                "[ViBao] \"{}\" is not a valid expr id (context: {})",
                raw, context
            ));
            None
        }
    }
}


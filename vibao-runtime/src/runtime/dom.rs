// Component ids are compile-time unique for static components, but a loop
// clones the same template N times at runtime. Components inside a loop need
// a fresh runtime id per clone so their prop scopes cannot overwrite each
// other in State::component_props.
static NEXT_COMPONENT_INSTANCE_ID: AtomicU64 = AtomicU64::new(1);

fn runtime_component_id(original: &str) -> String {
    let n = NEXT_COMPONENT_INSTANCE_ID.fetch_add(1, Ordering::Relaxed);
    format!("{}-r{}", original, n)
}
